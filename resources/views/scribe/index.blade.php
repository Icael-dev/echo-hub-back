                    <h2 id="endpoints-POSTapi-refresh">Refresh an access token using a valid refresh token.</h2>

<p>
</p>

<p>Implements token rotation: the old refresh token is revoked and a new one is issued.
Uses a database transaction to prevent race conditions (replay attacks).</p>
<p>Expects: { refresh_token: string }
Returns: { token, refresh_token, token_type, expires_in }</p>

<span id="example-requests-POSTapi-refresh">
<blockquote>Example request:</blockquote>


<div class="bash-example">
    <pre><code class="language-bash">curl --request POST \
    "http://localhost:8000/api/refresh" \
    --header "Content-Type: application/json" \
    --header "Accept: application/json" \
    --data "{
    \"refresh_token\": \"architecto\"
}"
</code></pre></div>


<div class="javascript-example">
